/**
 * @desc    Get task statistics
 * @route   GET /api/tasks/course/:courseId/statistics
 * @access  Private/Faculty
 */
exports.getTaskStatistics = async (req, res, next) => {
  try {
    const { courseId } = req.params;

    const course = await Course.findById(courseId);
    if (!course) {
      return res.status(404).json({
        success: false,
        message: 'Course not found'
      });
    }

    // Check permissions
    if (req.user.role === 'Faculty' && course.faculty.toString() !== req.user.id) {
      return res.status(403).json({
        success: false,
        message: 'Not authorized to view statistics for this course'
      });
    }

    const statistics = await TaskAssignment.aggregate([
      { $match: { course: course._id } },
      {
        $group: {
          _id: null,
          total: { $sum: 1 },
          assigned: { $sum: { $cond: [{ $eq: ['$status', 'Assigned'] }, 1, 0] } },
          inProgress: { $sum: { $cond: [{ $eq: ['$status', 'In Progress'] }, 1, 0] } },
          completed: { $sum: { $cond: [{ $eq: ['$status', 'Completed'] }, 1, 0] } },
          overdue: { $sum: { $cond: [{ $eq: ['$status', 'Overdue'] }, 1, 0] } },
          autoGenerated: { $sum: { $cond: ['$autoGenerated', 1, 0] } },
          manual: { $sum: { $cond: [{ $not: '$autoGenerated' }, 1, 0] } },
          avgScore: { $avg: '$bestScore' }
        }
      }
    ]);

    const stats = statistics.length > 0 ? statistics[0] : {
      total: 0,
      assigned: 0,
      inProgress: 0,
      completed: 0,
      overdue: 0,
      autoGenerated: 0,
      manual: 0,
      avgScore: 0
    };

    res.status(200).json({
      success: true,
      data: {
        course: {
          id: course._id,
          name: course.name,
          code: course.code
        },
        statistics: {
          total: stats.total,
          byStatus: {
            assigned: stats.assigned,
            inProgress: stats.inProgress,
            completed: stats.completed,
            overdue: stats.overdue
          },
          byType: {
            autoGenerated: stats.autoGenerated,
            manual: stats.manual
          },
          averageScore: Math.round(stats.avgScore * 100) / 100
        }
      }
    });
  } catch (error) {
    console.error('Get task statistics error:', error);
    res.status(500).json({
      success: false,
      message: 'Error fetching task statistics',
      error: error.message
    });
  }
};

