const TaskAssignment = require('../models/TaskAssignment');
const User = require('../models/User');
const Course = require('../models/Course');
const Subject = require('../models/Subject');
const Chapter = require('../models/Chapter');
const CIAExam = require('../models/CIAExam');
const StudentPerformance = require('../models/StudentPerformance');
const { validationResult } = require('express-validator');

/**
 * @desc    Create manual task assignment
 * @route   POST /api/tasks
 * @access  Private/Faculty
 */
exports.createTask = async (req, res, next) => {
  try {
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
      return res.status(400).json({
        success: false,
        errors: errors.array()
      });
    }

    const {
      student,
      course,
      subject,
      chapters,
      title,
      description,
      taskType,
      dueDate,
      priority,
      questions
    } = req.body;

    // Verify student exists
    const studentExists = await User.findById(student);
    if (!studentExists || studentExists.role !== 'Student') {
      return res.status(404).json({
        success: false,
        message: 'Student not found'
      });
    }

    // Verify course exists
    const courseExists = await Course.findById(course);
    if (!courseExists) {
      return res.status(404).json({
        success: false,
        message: 'Course not found'
      });
    }

    // Check permissions
    if (req.user.role === 'Faculty' && courseExists.faculty.toString() !== req.user.id) {
      return res.status(403).json({
        success: false,
        message: 'Not authorized to create tasks for this course'
      });
    }

    // Create task
    const task = await TaskAssignment.create({
      student,
      assignedBy: req.user.id,
      course,
      subject,
      chapters: chapters || [],
      title,
      description,
      taskType,
      generationReason: 'Manual',
      dueDate,
      priority: priority || 'Medium',
      questions: questions || [],
      autoGenerated: false
    });

    // Populate references
    await task.populate([
      { path: 'student', select: 'name rollNumber email' },
      { path: 'assignedBy', select: 'name email' },
      { path: 'course', select: 'name code' },
      { path: 'subject', select: 'name code' },
      { path: 'chapters', select: 'title chapterNumber' }
    ]);

    res.status(201).json({
      success: true,
      message: 'Task created successfully',
      data: task
    });
  } catch (error) {
    console.error('Create task error:', error);
    res.status(500).json({
      success: false,
      message: 'Error creating task',
      error: error.message
    });
  }
};

/**
 * @desc    Auto-generate tasks for weak students (CRITICAL FEATURE)
 * @route   POST /api/tasks/auto-generate
 * @access  Private/Faculty
 */
exports.autoGenerateTasks = async (req, res, next) => {
  try {
    const { course, exam, chapter, threshold } = req.body;

    if (!course) {
      return res.status(400).json({
        success: false,
        message: 'Course ID is required'
      });
    }

    // Verify course exists
    const courseExists = await Course.findById(course).populate('faculty');
    if (!courseExists) {
      return res.status(404).json({
        success: false,
        message: 'Course not found'
      });
    }

    // Check permissions
    if (req.user.role === 'Faculty' && courseExists.faculty._id.toString() !== req.user.id) {
      return res.status(403).json({
        success: false,
        message: 'Not authorized to generate tasks for this course'
      });
    }

    const performanceThreshold = threshold || 50;
    const generatedTasks = [];

    if (exam) {
      // Generate tasks based on exam performance
      const examExists = await CIAExam.findById(exam);
      if (!examExists) {
        return res.status(404).json({
          success: false,
          message: 'Exam not found'
        });
      }

      const ExamMarks = require('../models/ExamMarks');
      const weakStudents = await ExamMarks.getWeakStudentsByChapter(exam, performanceThreshold);

      for (const chapterData of weakStudents) {
        for (const student of chapterData.weakStudents) {
          const task = await TaskAssignment.create({
            student: student.studentId,
            assignedBy: req.user.id,
            course,
            subject: examExists.subject,
            chapters: [chapterData.chapter._id],
            title: `Practice Task - ${chapterData.chapter.title}`,
            description: `Based on your performance in ${examExists.title}, practice questions from this chapter to improve your understanding. Current score: ${student.percentage.toFixed(2)}%`,
            taskType: 'MCQ Practice',
            generationReason: 'Poor CIA Performance',
            triggerExam: exam,
            dueDate: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // 7 days
            priority: student.percentage < 40 ? 'High' : 'Medium',
            autoGenerated: true
          });

          await task.populate([
            { path: 'student', select: 'name rollNumber email' },
            { path: 'chapters', select: 'title chapterNumber' }
          ]);

          generatedTasks.push(task);
        }
      }
    } else if (chapter) {
      // Generate tasks based on chapter performance
      const chapterExists = await Chapter.findById(chapter);
      if (!chapterExists) {
        return res.status(404).json({
          success: false,
          message: 'Chapter not found'
        });
      }

      const weakStudents = await StudentPerformance.find({
        course,
        'chapterPerformance.chapter': chapter,
        'chapterPerformance.percentage': { $lt: performanceThreshold }
      }).populate('student', 'name rollNumber email');

      for (const performance of weakStudents) {
        const chapterPerf = performance.chapterPerformance.find(
          cp => cp.chapter.toString() === chapter
        );

        const task = await TaskAssignment.create({
          student: performance.student._id,
          assignedBy: req.user.id,
          course,
          subject: performance.subject,
          chapters: [chapter],
          title: `Practice Task - ${chapterExists.title}`,
          description: `Your performance in ${chapterExists.title} needs improvement. Complete this practice task to strengthen your understanding. Current score: ${chapterPerf.percentage.toFixed(2)}%`,
          taskType: 'MCQ Practice',
          generationReason: 'Weak Chapter',
          dueDate: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000),
          priority: chapterPerf.percentage < 40 ? 'High' : 'Medium',
          autoGenerated: true
        });

        await task.populate([
          { path: 'student', select: 'name rollNumber email' },
          { path: 'chapters', select: 'title chapterNumber' }
        ]);

        generatedTasks.push(task);
      }
    } else {
      // Generate tasks for all weak students in course
      const weakStudents = await StudentPerformance.find({
        course,
        overallPerformance: { $lt: performanceThreshold }
      }).populate('student', 'name rollNumber email')
        .populate('weakChapters', 'title chapterNumber');

      for (const performance of weakStudents) {
        if (performance.weakChapters.length > 0) {
          const task = await TaskAssignment.create({
            student: performance.student._id,
            assignedBy: req.user.id,
            course,
            subject: performance.subject,
            chapters: performance.weakChapters.map(c => c._id),
            title: `Practice Task - Overall Improvement`,
            description: `Your overall performance needs improvement. Focus on the weak chapters to improve your understanding. Current score: ${performance.overallPerformance.toFixed(2)}%`,
            taskType: 'MCQ Practice',
            generationReason: 'Weak Chapter',
            dueDate: new Date(Date.now() + 14 * 24 * 60 * 60 * 1000), // 14 days
            priority: performance.overallPerformance < 40 ? 'High' : 'Medium',
            autoGenerated: true
          });

          await task.populate([
            { path: 'student', select: 'name rollNumber email' },
            { path: 'chapters', select: 'title chapterNumber' }
          ]);

          generatedTasks.push(task);
        }
      }
    }

    res.status(201).json({
      success: true,
      message: `${generatedTasks.length} tasks generated successfully`,
      count: generatedTasks.length,
      data: generatedTasks
    });
  } catch (error) {
    console.error('Auto-generate tasks error:', error);
    res.status(500).json({
      success: false,
      message: 'Error generating tasks',
      error: error.message
    });
  }
};

